/**
 * RepairTypes.ts — Data Schema and Interfaces for Adaptive Verification & Repair Engine
 *
 * Enforces structured multi-source evidence reporting, confidence scoring, logical
 * action repair graphs (zero shell commands), and comprehensive repair history metrics.
 */

import { FailureDiagnosis } from './FailureClassification';

export type VerificationStage = 'immediate' | 'delayed' | 'post-repair' | 'pre-consumption';

export type RetryMode = 'immediate' | 'delayed' | 'exponential-backoff' | 'dependency-triggered' | 'user-approval';

export interface RetryPolicy {
  readonly mode: RetryMode;
  readonly maxAttempts: number;
  readonly baseDelayMs: number;
  readonly maxDelayMs?: number;
  readonly requireUserConfirmation?: boolean;
}

/**
 * Every verification outcome must synthesize multiple sources of evidence, providing explicit
 * confidence scoring so the Runtime can evaluate uncertainty.
 */
export interface AdaptiveVerificationResult {
  readonly success: boolean;
  /** Confidence score between 0.0 (high uncertainty) and 1.0 (verified across all 5 independent sources) */
  readonly confidence: number;
  /** Explicit logical deduction summarizing why postconditions passed or failed */
  readonly reason: string;
  readonly reasoning: string;
  /** Array of verified evidence statements harvested from Capabilities, State Engine, Events, & Outputs */
  readonly evidence: string[];
  /** Timestamp when verification completed */
  readonly timestamp: number;
  /** Which stage of the verification lifecycle this result represents */
  readonly stage: VerificationStage;
  /** Verified parameter payload to be safely published into ExecutionContext */
  readonly verifiedOutputs: Record<string, unknown>;
}

/**
 * Logical representation of a recovery node. Never contains shell commands or direct OS invocations.
 */
export interface RepairNode {
  readonly id: string;
  /** Strongly typed Action ID from the Phase 3 Action Registry (e.g. 'network.wifi.on', 'app.restart') */
  readonly actionId: string;
  readonly parameters: Record<string, unknown>;
  readonly description: string;
  readonly dependencies: string[];
}

/**
 * Complete logical repair graph generated by the RepairPlanner when a failure occurs.
 */
export interface RepairGraph {
  readonly id: string;
  readonly targetActionId: string;
  readonly diagnosis: FailureDiagnosis;
  readonly nodes: RepairNode[];
  readonly strategyName: string;
  readonly createdTimestamp: number;
}

/**
 * Structured record of every attempted repair execution, preserved in historical storage
 * to power long-term adaptive optimization and pattern learning.
 */
export interface RepairHistoryEntry {
  readonly id: string;
  readonly failure: FailureDiagnosis;
  readonly strategy: string;
  readonly repairGraph?: RepairGraph;
  readonly outcome: 'success' | 'failed' | 'escalated';
  readonly latencyMs: number;
  readonly timestamp: number;
  readonly retryAttempts: number;
}

export interface RecoveryResult {
  readonly success: boolean;
  readonly resolutionStrategy: string;
  readonly durationMs: number;
  readonly verification: AdaptiveVerificationResult;
  readonly repairGraph?: RepairGraph;
  readonly warnings: string[];
  readonly error?: string;
}
